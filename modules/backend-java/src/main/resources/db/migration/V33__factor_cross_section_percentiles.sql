ALTER TABLE factor_cross_section_score
    ADD COLUMN factor_percentiles JSON DEFAULT NULL
        COMMENT '各因子 L2 横截面百分位 {"MOM_20":87.3,...}，键为 FactorId.name()；NULL=该行未记录逐因子明细（旧行）。用于逐因子 Rank IC 诊断';
