-- MP-015: Event-driven portfolio backtest (pragmatic MVP)
CREATE TABLE IF NOT EXISTS portfolio_backtest_run (
    id                  BIGINT AUTO_INCREMENT PRIMARY KEY,
    run_id              VARCHAR(40)  NOT NULL,
    strategy_type       VARCHAR(32)  DEFAULT NULL,
    start_date          DATE         NOT NULL,
    end_date            DATE         NOT NULL,
    horizon             INT          NOT NULL DEFAULT 2,
    initial_cash        DOUBLE       NOT NULL,
    max_positions       INT          NOT NULL,
    weighting           VARCHAR(20)  NOT NULL DEFAULT 'EQUAL',
    commission_rate     DOUBLE       NOT NULL,
    sell_tax_rate       DOUBLE       NOT NULL,
    slippage_rate       DOUBLE       NOT NULL,
    cost_version        VARCHAR(40)  NOT NULL,
    execution_version   VARCHAR(40)  NOT NULL,
    final_nav           DOUBLE       DEFAULT NULL,
    total_return        DOUBLE       DEFAULT NULL,
    max_drawdown        DOUBLE       DEFAULT NULL,
    total_trades        INT          DEFAULT NULL,
    reject_count        INT          DEFAULT NULL,
    summary_json        LONGTEXT     DEFAULT NULL,
    nav_json            LONGTEXT     DEFAULT NULL,
    orders_json         LONGTEXT     DEFAULT NULL,
    status              VARCHAR(20)  NOT NULL DEFAULT 'COMPLETED',
    created_at          DATETIME(6)  DEFAULT NULL,
    UNIQUE KEY uk_portfolio_backtest_run_id (run_id),
    INDEX idx_portfolio_backtest_created (created_at)
) ENGINE=InnoDB DEFAULT CHARSET=utf8mb4 COMMENT='事件驱动组合回测运行';
